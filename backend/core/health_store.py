import sqlite3
import json
import os
import datetime
from typing import Dict, List, Optional, Any
from core.database import db_manager
from core.logger import get_logger

logger = get_logger("HealthStore")

DB_PATH = "data/health_guardian.db"

class HealthStore:
    """
    Tracks daily logs of food items, symptoms, and mood.
    Falls back to SQLite if Supabase is offline.
    """
    def __init__(self):
        os.makedirs(os.path.dirname(DB_PATH), exist_ok=True)
        self._init_db()

    def _connect(self):
        return sqlite3.connect(DB_PATH)

    def _init_db(self):
        with self._connect() as conn:
            c = conn.cursor()
            c.execute("""
                CREATE TABLE IF NOT EXISTS health_logs (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    date TEXT UNIQUE,
                    meals TEXT, -- JSON list of meals
                    symptoms TEXT, -- JSON list of symptoms
                    mood TEXT, -- Mood state
                    analysis_plan TEXT, -- Daily analysis and tips generated by mother persona
                    updated_at TEXT
                )
            """)
            conn.commit()

    def get_log(self, date_str: str) -> Dict[str, Any]:
        """Returns the health log for a specific date, or a default blank log."""
        # 1. Try Supabase
        if db_manager.supabase:
            try:
                res = db_manager.supabase.table("health_logs").select("*").eq("date", date_str).execute()
                if res.data:
                    row = res.data[0]
                    return {
                        "date": row["date"],
                        "meals": json.loads(row.get("meals") or "[]"),
                        "symptoms": json.loads(row.get("symptoms") or "[]"),
                        "mood": row.get("mood", "neutral"),
                        "analysis_plan": row.get("analysis_plan", "")
                    }
            except Exception as e:
                logger.warning(f"Supabase health fetch failed: {e}")

        # 2. Try SQLite
        with self._connect() as conn:
            conn.row_factory = sqlite3.Row
            c = conn.cursor()
            row = c.execute("SELECT * FROM health_logs WHERE date = ?", (date_str,)).fetchone()
            if row:
                return {
                    "date": row["date"],
                    "meals": json.loads(row["meals"] or "[]"),
                    "symptoms": json.loads(row["symptoms"] or "[]"),
                    "mood": row["mood"],
                    "analysis_plan": row["analysis_plan"]
                }

        # Default Blank Log
        return {
            "date": date_str,
            "meals": [],
            "symptoms": [],
            "mood": "neutral",
            "analysis_plan": ""
        }

    def save_log(self, log: Dict[str, Any]):
        """Persists the health log to both SQLite and Supabase."""
        date_str = log["date"]
        meals_json = json.dumps(log.get("meals", []))
        symptoms_json = json.dumps(log.get("symptoms", []))
        mood = log.get("mood", "neutral")
        analysis_plan = log.get("analysis_plan", "")
        now = datetime.datetime.utcnow().isoformat()

        # 1. Save SQLite
        with self._connect() as conn:
            c = conn.cursor()
            c.execute("""
                INSERT OR REPLACE INTO health_logs (date, meals, symptoms, mood, analysis_plan, updated_at)
                VALUES (?, ?, ?, ?, ?, ?)
            """, (date_str, meals_json, symptoms_json, mood, analysis_plan, now))
            conn.commit()

        # 2. Save Supabase
        if db_manager.supabase:
            try:
                payload = {
                    "date": date_str,
                    "meals": meals_json,
                    "symptoms": symptoms_json,
                    "mood": mood,
                    "analysis_plan": analysis_plan,
                    "updated_at": now
                }
                db_manager.supabase.table("health_logs").upsert(payload).execute()
            except Exception as e:
                logger.warning(f"Supabase health sync failed: {e}")

    def add_meal(self, date_str: str, meal: Dict[str, Any]):
        log = self.get_log(date_str)
        log["meals"].append(meal)
        self.save_log(log)

    def add_symptom(self, date_str: str, symptom: str):
        log = self.get_log(date_str)
        if symptom not in log["symptoms"]:
            log["symptoms"].append(symptom)
        self.save_log(log)

    def get_recent_history(self, limit: int = 7) -> List[Dict[str, Any]]:
        """Returns logs from the last N days."""
        history = []
        with self._connect() as conn:
            conn.row_factory = sqlite3.Row
            c = conn.cursor()
            rows = c.execute("SELECT * FROM health_logs ORDER BY date DESC LIMIT ?", (limit,)).fetchall()
            for r in rows:
                history.append({
                    "date": r["date"],
                    "meals": json.loads(r["meals"] or "[]"),
                    "symptoms": json.loads(r["symptoms"] or "[]"),
                    "mood": r["mood"],
                    "analysis_plan": r["analysis_plan"]
                })
        return history

# Global Instance
health_store = HealthStore()
